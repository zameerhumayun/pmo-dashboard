/* =====================================================================
   PMO Dashboard - printable project report
   "Print / Save as PDF" uses the browser's own print dialog (window.print).
   The print stylesheet in style.css hides the sidebar, header and buttons.
   ===================================================================== */

App.views.report = function ($v) {
  const p = App.current(), c = Projects.calc(p), alerts = Alerts.forProject(p);
  const risks = Projects.risksOf(p.id), checks = Projects.completionChecks(p);
  const updates = Comments.of(p.id).slice(0, 5);
  const statusBadge = (t, s) => badge(t, HEALTH_COLOR[s]);

  $v.html(`<div class="toolbar noprint"><h2>Project Report</h2>${App.projectSelect()}<button class="btn" onclick="window.print()">🖨️ Print / Save as PDF</button></div>
  <div class="card report">
    <div style="display:flex;justify-content:space-between;flex-wrap:wrap;gap:10px">
      <div><h1 class="t">Project Status Report</h1><p class="sub" style="margin:4px 0 0">${esc(p.name)} (${esc(p.id)})</p></div>
      <div class="small muted" style="text-align:right">Report date: ${U.date(U.today())}<br>Prepared by: Project Management Office</div></div>

    <h2>1. Project Information</h2>
    <table class="kv"><tr><td>Project Manager</td><td>${esc(p.manager)}</td></tr><tr><td>Department</td><td>${esc(p.dept) || "—"}</td></tr>
      <tr><td>Description</td><td>${esc(p.desc) || "—"}</td></tr><tr><td>Current Phase</td><td>${esc(p.phase)}</td></tr>
      <tr><td>Project Status</td><td>${badge(p.status, Projects.statusColor(p.status))}${p.completedAt ? " on " + U.date(p.completedAt) : ""}</td></tr>
      <tr><td>Overall Health</td><td>${Projects.healthBadge(c)}</td></tr></table>

    <h2>2. Project Progress & Schedule Performance</h2>
    <div class="grid2" style="margin:0"><div>
      <table class="kv"><tr><td>Start date</td><td>${U.date(p.start)}</td></tr><tr><td>Expected end date</td><td>${U.date(p.end)}</td></tr>
        <tr><td>Forecast finish</td><td>${c.forecast ? U.date(c.forecast) : "Not enough progress to estimate"}</td></tr>
        <tr><td>Planned progress</td><td>${P(p.pp)}</td></tr><tr><td>Actual progress</td><td>${P(p.ap)}</td></tr>
        <tr><td>Progress variance</td><td>${c.progVar > 0 ? "+" : ""}${P(c.progVar)}</td></tr>
        <tr><td>Schedule status</td><td>${statusBadge(c.schedStatus, c.schedSev)}</td></tr></table></div>
      <div class="chart-box sm"><canvas id="repPie"></canvas></div></div>

    <h2>3. Budget Performance</h2>
    <table class="kv"><tr><td>Approved budget</td><td>${M(p.budget)}</td></tr><tr><td>Planned cost</td><td>${M(p.planned)}</td></tr>
      <tr><td>Actual cost</td><td>${M(p.actual)}</td></tr><tr><td>Remaining budget</td><td>${M(c.remaining)}${c.remaining < 0 ? " (over budget)" : ""}</td></tr>
      <tr><td>Budget utilization</td><td>${P(c.util)}</td></tr><tr><td>Cost status</td><td>${statusBadge(c.costStatus, c.costSev)}</td></tr></table>

    <h2>4. Risk Summary</h2>
    <p class="small">Open risks: ${c.rc.High} High, ${c.rc.Medium} Medium, ${c.rc.Low} Low · Risk score ${c.riskScore} → ${badge(c.riskLevel, riskColor(c.riskLevel))} · ${risks.length - c.openRisks.length} resolved</p>
    ${c.openRisks.length ? `<table><tr><th>ID</th><th>Risk</th><th>Category</th><th>Severity</th><th>Mitigation Action</th><th>Status</th></tr>
      ${c.openRisks.map(r => `<tr><td>${esc(r.id)}</td><td>${esc(r.desc)}</td><td>${esc(r.cat)}</td><td>${badge(r.level, riskColor(r.level))}</td><td>${esc(r.mit) || "—"}</td><td>${esc(r.status)}</td></tr>`).join("")}</table>`
      : `<p>No open risks.</p>`}

    <h2>5. Open Issues</h2>
    ${c.openIssues.length ? `<table><tr><th>ID</th><th>Issue</th><th>Severity</th><th>Suggested Resolution</th><th>Status</th></tr>
      ${c.openIssues.map(i => `<tr><td>${esc(i.id)}</td><td>${esc(i.desc)}</td><td>${badge(i.severity, riskColor(i.severity))}</td><td>${esc(i.resolution) || "—"}</td><td>${esc(i.status)}</td></tr>`).join("")}</table>`
      : `<p>No open issues.</p>`}

    <h2>6. Alerts & Recommendations</h2>
    ${alerts.length ? `<table><tr><th>Alert</th><th>Details</th><th>Recommended corrective action</th></tr>
      ${alerts.map(a => `<tr><td><b>${esc(a.title)}</b></td><td>${esc(a.msg)}</td><td>${esc(a.rec)}</td></tr>`).join("")}</table>`
      : "<p>No alerts were triggered.</p>"}

    <h2>7. Latest Project Updates</h2>
    <p><b>Latest remarks:</b> ${esc(p.update) || "—"}</p>
    ${updates.length ? updates.map(u => `<p class="small"><b>${U.dateTime(u.at)} · ${esc(u.type)} · ${esc(u.author)}:</b> ${esc(u.text)}</p>`).join("") : '<p class="muted">No comments or updates recorded.</p>'}

    <h2>8. Completion Readiness</h2>
    <ul class="clean">${checks.map(k => `<li>${k.ok ? "✅" : "❌"} ${esc(k.text)}${k.ok ? "" : ` - <span class="small">${esc(k.problem)}</span>`}</li>`).join("")}</ul>

    <div class="foot">Generated by the PMO Dashboard · Alerts are rule-based (IF / ELSE conditions), not AI predictions</div>
  </div>`);
  Charts.progressPie("repPie", p.ap);
};
